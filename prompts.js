// ตัวช่วยจัดระยะข้อความ
function dedent(str) {
  const lines = str
    .replace(/^\n/, "")
    .replace(/\n[ \t]*$/, "")
    .split("\n");

  const indents = lines
    .filter((l) => l.trim())
    .map((l) => l.match(/^[ \t]*/)[0].length);

  const min = indents.length ? Math.min(...indents) : 0;

  return lines.map((l) => l.slice(min)).join("\n");
}

